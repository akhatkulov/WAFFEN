# ---- recommend_plan -------------------------------------------------------

def test_recommend_plan_with_known_vendor():
    guesses = [WafGuess("Cloudflare", 0.9, "header")]
    plan = recommend_plan(guesses)
    assert plan["vendor"] == "Cloudflare"
    assert plan["body_limit"] == 131072
    assert len(plan["suggested_mutators"]) > 0


def test_recommend_plan_empty_guesses():
    plan = recommend_plan([])
    assert plan["vendor"] is None
    assert plan["body_limit"] == 8192


def test_recommend_plan_unknown_vendor():
    guesses = [WafGuess("SomeNewWAF", 0.5, "body")]
    plan = recommend_plan(guesses)
    assert plan["vendor"] == "SomeNewWAF"
    assert plan["body_limit"] == 8192  # falls back to default
