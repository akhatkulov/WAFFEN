"""Tests for the WAF fingerprint database completeness and matching logic."""
import re

import pytest

from waffen.recon.fingerprint import (
    SIGNATURES,
    WafGuess,
    FPResponse,
    fingerprint,
    _behavioral_waf_guess,
    recommend_plan,
    BODY_LIMITS,
    WEAK_HINTS,
)


# ---- database completeness ------------------------------------------------

def test_signature_count_at_least_100():
    assert len(SIGNATURES) >= 100, f"Expected 100+ signatures, got {len(SIGNATURES)}"


def test_all_signatures_have_name():
    for i, sig in enumerate(SIGNATURES):
        assert sig.get("name"), f"Signature index {i} missing name"


def test_all_signatures_have_at_least_one_pattern():
    for sig in SIGNATURES:
        patterns = sig.get("header", []) + sig.get("cookie", []) + sig.get("body", [])
        assert patterns, f"Signature '{sig['name']}' has no patterns"


def test_no_duplicate_names():
    names = [s["name"] for s in SIGNATURES]
    dupes = [n for n in names if names.count(n) > 1]
    assert not dupes, f"Duplicate signature names: {set(dupes)}"


def test_all_patterns_are_valid_regex():
    for sig in SIGNATURES:
        for key in ("header", "cookie", "body"):
            for pat in sig.get(key, []):
                try:
                    re.compile(pat, re.I)
                except re.error as e:
                    pytest.fail(f"Invalid regex in {sig['name']}.{key}: {pat!r} -> {e}")


