def test_no_match_returns_empty_or_generic():
    benign = FPResponse("200", "Hello world", {"server": "nginx"})
    malicious = FPResponse("200", "Hello world", {"server": "nginx"})
    guesses = fingerprint(None, sender=_mock_sender(benign, malicious))
    # Either empty or only generic behavioral
    for g in guesses:
        assert g.confidence <= 0.3, f"Unexpected high-confidence match: {g}"


def test_behavioral_fallback_on_block():
    benign = FPResponse("200", "OK", {"server": "nginx"})
    malicious = FPResponse("403", "Forbidden", {"server": "nginx"})
    guesses = fingerprint(None, sender=_mock_sender(benign, malicious))
    assert any("generic" in g.name.lower() or "unknown" in g.name.lower() for g in guesses)


def test_confidence_ordered_descending():
    benign = FPResponse("200", "", {"server": "cloudflare", "cf-ray": "x"})
    malicious = FPResponse("403", "Attention Required! | Cloudflare", {"server": "cloudflare"})
    guesses = fingerprint(None, sender=_mock_sender(benign, malicious))
    for i in range(len(guesses) - 1):
        assert guesses[i].confidence >= guesses[i + 1].confidence


