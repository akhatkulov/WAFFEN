# Default transport: curl, same pattern as Oracle._curl_send, but captures
# response headers (-i) since vendor fingerprints often live there.
# ---------------------------------------------------------------------------
_STATUS_RE = re.compile(r"HTTP/\S+\s+(\d+)")


def _parse_curl_i(out: str) -> FPResponse:
    """Parse `curl -i` output into (code, headers, body).

    Handles the common case of one leading header block (does not attempt to
    unwind multiple redirect hops — good enough for vendor fingerprinting,
    where the block/challenge page is usually the final response anyway).
    """
    for sep in ("\r\n\r\n", "\n\n"):
        if sep in out:
            header_blob, _, body = out.partition(sep)
            break
    else:
        header_blob, body = "", out

    lines = header_blob.splitlines()
    code = "000"
    headers: dict[str, str] = {}
    if lines:
        m = _STATUS_RE.match(lines[0])
        if m:
            code = m.group(1)
        for line in lines[1:]:
            if ":" not in line:
                continue
            k, _, v = line.partition(":")
            k, v = k.strip().lower(), v.strip()
            headers[k] = f"{headers[k]}; {v}" if k in headers else v
    return FPResponse(code, body, headers)


def _curl_sender(target):
    def sender(payload: str) -> FPResponse:
        t = target
        url = t.url()
        qp = urllib.parse.urlencode({t.param: payload})
        sep = "&" if "?" in url else "?"
        sec = t.curl_sec(with_i=True) if hasattr(t, "curl_sec") else "-ski"
        cmd = ["curl", sec, "-m", str(t.timeout), "-A", t.user_agent,
               "-X", t.method, f"{url}{sep}{qp}"]
        try:
            out = subprocess.run(cmd, capture_output=True, text=True,
                                  timeout=t.timeout + 5).stdout
        except Exception:
            return FPResponse("000", "", {})
        return _parse_curl_i(out)
    return sender


# A mildly-malicious probe: enough signal (SQLi/XSS/traversal tokens) to
# trip a WAF's generic rules and surface its block/challenge page, without
# being a real, class-specific attack.
_BENIGN_PROBE = "waffen-recon-probe"
_MALICIOUS_PROBE = "' OR 1=1-- <script>alert(1)</script> ../../../../etc/passwd"

# Status codes a WAF typically returns when it BLOCKS (as opposed to the origin
# erroring). Used for the behavioral fallback below.
_BLOCK_CODES = {"403", "406", "501", "419", "429", "503", "999"}


def _behavioral_waf_guess(responses) -> "WafGuess | None":
    """Vendor-agnostic 'is a WAF inline?' fallback via a benign/malicious differential.

    Many of the most common deployments expose NO vendor signature at all — e.g.
    OWASP CRS / ModSecurity behind nginx just returns nginx's generic 403 page with
    `Server: nginx` and no distinguishing header or body text. A signature-only
    fingerprinter then reports 'no WAF', which is actively misleading: the attack
    probe plainly got blocked while the benign one passed. When the benign probe
    reaches the origin (2xx/3xx/404) but the malicious probe comes back with a
    block-ish status the benign one did NOT, that difference is itself evidence of
    an inline WAF — reported at low confidence, vendor unidentified (this is exactly
    the generic-detection fallback wafw00f uses). Conservative on purpose: an app
    error on the malicious probe (500/400) is not in `_BLOCK_CODES`, so it never
    fabricates a WAF where the origin merely choked."""
    if len(responses) < 2:
        return None
    benign, malicious = responses[0], responses[1]
    bc = (getattr(benign, "code", "") or "")
    mc = (getattr(malicious, "code", "") or "")
    benign_passed = bc[:1] in ("2", "3") or bc == "404"
    malic_blocked = mc in _BLOCK_CODES and mc != bc
    if not (benign_passed and malic_blocked):
        return None
    srv = ""
    mh = getattr(malicious, "headers", None) or {}
    if isinstance(mh, dict) and mh.get("server"):
        srv = f", server={mh['server']!r}"
    return WafGuess(
        "Generic/Unknown WAF", 0.3,
        f"behavioral: benign HTTP {bc} reached origin, attack probe -> HTTP {mc} blocked{srv} "
        "(a WAF is inline; vendor not identified by any known signature)")


def fingerprint(target, sender=None) -> list["WafGuess"]:
    """Identify the WAF (if any) in front of `target`.

    Sends a benign request and a mildly-malicious probe, then scores every
    entry in SIGNATURES against both responses. Returns guesses sorted by
    confidence, descending; empty list if nothing matched.

    `sender`, if given, must be `sender(payload) -> obj` where obj has
    `.code`, `.body`, and optionally `.headers` (a dict). This lets tests
    (and offline use) plug in a fake transport — including plain
    `waffen.core.oracle.Response` objects, which have no `.headers`; those
    are treated as having no headers (body/code-only signatures still work).
    """
    send = sender or _curl_sender(target)
    responses = [send(_BENIGN_PROBE), send(_MALICIOUS_PROBE)]

    guesses: list[WafGuess] = []
    for sig in SIGNATURES:
        hits: list[str] = []
        for resp in responses:
            body = getattr(resp, "body", "") or ""
            headers = getattr(resp, "headers", None) or {}
            header_blob = "\n".join(f"{k}: {v}" for k, v in headers.items())
            cookie_blob = headers.get("set-cookie", "") if isinstance(headers, dict) else ""

            for pat in sig.get("body", []):
                if re.search(pat, body, re.I):
                    hits.append(f"body~/{pat}/")
            for pat in sig.get("header", []):
                if re.search(pat, header_blob, re.I | re.M):
                    hits.append(f"header~/{pat}/")
            for pat in sig.get("cookie", []):
                if re.search(pat, cookie_blob, re.I):
                    hits.append(f"cookie~/{pat}/")

        if not hits:
            continue
        total_patterns = sum(len(sig.get(k, [])) for k in ("body", "header", "cookie")) or 1
        # distinct pattern hits (dedupe across the two probes), capped at 1.0
        confidence = min(len(dict.fromkeys(hits)) / total_patterns, 1.0)
        guesses.append(WafGuess(sig["name"], round(confidence, 2), "; ".join(dict.fromkeys(hits))))

    # Behavioral fallback: if no vendor signature matched but the attack probe was
    # clearly blocked while the benign one passed, report a generic inline WAF
    # instead of an empty (misleading "no WAF") result.
    if not guesses:
        g = _behavioral_waf_guess(responses)
        if g is not None:
            guesses.append(g)

    guesses.sort(key=lambda g: g.confidence, reverse=True)
    return guesses


