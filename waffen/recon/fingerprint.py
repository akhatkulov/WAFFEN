"""wafw00f-style WAF fingerprinting.

Sends a benign probe and a mildly-malicious probe at the target and matches
headers, cookies, and response body against a small, extensible SIGNATURES
table of known WAF vendors. Returns ranked guesses — an empty list means no
known signature matched (the WAF may be unknown/custom, or there may be no
WAF at all).

`Response` from waffen.core.oracle carries only status/size/time/body (no
headers), which is enough for body-based signatures (e.g. a vendor block
page) but not header/cookie-based ones (e.g. a `cf-ray` header). So the
default transport here is a small curl wrapper, following the same
subprocess-curl pattern as `waffen.core.oracle.Oracle._curl_send`, that
additionally captures response headers. Callers needing offline/test control
can pass any `sender(payload) -> object` with `.code`, `.body`, and optional
`.headers` (dict); `fingerprint()` degrades gracefully (treats headers as
empty) when a fake sender doesn't provide them — exactly what the test suite
does, reusing `waffen.core.oracle.Response`.
"""
from __future__ import annotations

import re
import subprocess
import urllib.parse
from dataclasses import dataclass, field


@dataclass
class WafGuess:
    name: str
    confidence: float
    evidence: str


@dataclass
class FPResponse:
    """Minimal response shape fingerprint() needs: status + body + headers."""
    code: str
    body: str
    headers: dict = field(default_factory=dict)


